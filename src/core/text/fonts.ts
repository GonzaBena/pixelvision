/**
 * Fuentes bitmap embebidas.
 *
 * El texto de pixel art no puede venir de una TTF: el rasterizado con
 * antialiasing ensucia los bordes y a tamaños chicos se vuelve ilegible. Estos
 * glifos están dibujados píxel a píxel, así que siempre salen nítidos.
 *
 * Formato de autoría: filas separadas por `|`, `#` = píxel encendido.
 */

export interface Glyph {
  w: number
  h: number
  /** w*h bytes, 1 = encendido. */
  data: Uint8Array
}

export interface BitmapFont {
  id: string
  label: string
  w: number
  h: number
  /** Distancia desde la línea base superior hasta el tope de las mayúsculas. */
  glyphs: Map<number, Glyph>
  fallback: Glyph
}

