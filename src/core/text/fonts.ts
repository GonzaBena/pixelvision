// ---------------------------------------------------------------------------

function compileGlyph(src: string, w: number, h: number): Glyph {
  const rows = src.split('|')
  const data = new Uint8Array(w * h)
  for (let y = 0; y < h; y++) {
    const row = rows[y] ?? ''
    for (let x = 0; x < w; x++) {
      if (row[x] === '#') data[y * w + x] = 1
    }
  }
  return { w, h, data }
}

function compileFont(
  id: string,
  label: string,
  w: number,
  h: number,
  src: Record<string, string>,
  fallback: string,
): BitmapFont {
  const glyphs = new Map<number, Glyph>()
  for (const [ch, art] of Object.entries(src)) {
    glyphs.set(ch.codePointAt(0)!, compileGlyph(art, w, h))
  }
  return { id, label, w, h, glyphs, fallback: compileGlyph(fallback, w, h) }
}

export const FONT_5X7 = compileFont('pv5x7', 'PV 5×7', 5, 7, SRC_5X7, FALLBACK_5X7)
export const FONT_3X5 = compileFont('pv3x5', 'PV 3×5', 3, 5, SRC_3X5, FALLBACK_3X5)

export function getGlyph(font: BitmapFont, codePoint: number): Glyph {
  const direct = font.glyphs.get(codePoint)
  if (direct) return direct
  // La fuente diminuta sólo tiene caja alta: las minúsculas caen en su mayúscula.
  const upper = String.fromCodePoint(codePoint).toUpperCase().codePointAt(0)
  if (upper !== undefined && upper !== codePoint) {
    const alt = font.glyphs.get(upper)
    if (alt) return alt
  }
  return font.fallback
}

